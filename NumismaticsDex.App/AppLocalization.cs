    public static string Get(string key, string languageTag)
    {
        var value = Texts[key];
        if (languageTag == "ja-JP")
        {
            return JapaneseTexts.TryGetValue(key, out var japanese) ? japanese : value.English;
        }

        return languageTag switch
        {
            "zh-TW" => value.Traditional,
            "en-US" => value.English,
            _ => value.Simplified
        };
    }

