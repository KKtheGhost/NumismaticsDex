    public static string IssueDate(Banknote banknote, string languageTag)
    {
        var sourceDate = banknote.IssueDate;
        if (languageTag == "en-US")
        {
            return sourceDate;
        }
        if (IssueDateTranslations.TryGetValue(sourceDate, out var translatedDate))
        {
            return languageTag switch
            {
                "zh-TW" => translatedDate.Traditional,
                "ja-JP" => translatedDate.Japanese,
                _ => translatedDate.Simplified
            };
        }

        var republicDate = Regex.Match(sourceDate, @"Year\s+(?<year>[0-9]+)\s+of\s+the\s+Republic", RegexOptions.IgnoreCase);
        if (republicDate.Success)
        {
            var years = Regex.Matches(sourceDate, @"\b(?:18|19|20)[0-9]{2}\b");
            var westernYear = years.Count > 0 ? years[years.Count - 1].Value : banknote.Year?.ToString() ?? "";
            var republicYear = ToChineseNumber(int.Parse(republicDate.Groups["year"].Value));
            if (languageTag == "ja-JP")
            {
                return $"中華民国{republicYear}年（{westernYear}年）";
            }

            return languageTag == "zh-TW"
                ? $"民國{republicYear}年（{westernYear}）"
                : $"民国{republicYear}年（{westernYear}）";
        }

        var combinedRepublic = Regex.Match(sourceDate,
            @"year\s+(?<first>[0-9]+)\s*&\s*(?<second>[0-9]+)\s+of\s+the\s+Republic\s*=\s*(?<firstYear>[0-9]{4})\s*&\s*(?<secondYear>[0-9]{4})",
            RegexOptions.IgnoreCase);
        if (combinedRepublic.Success)
        {
            var firstYear = ToChineseNumber(int.Parse(combinedRepublic.Groups["first"].Value));
            var secondYear = ToChineseNumber(int.Parse(combinedRepublic.Groups["second"].Value));
            var firstDate = combinedRepublic.Groups["firstYear"].Value;
            var secondDate = combinedRepublic.Groups["secondYear"].Value;
            var eraName = languageTag switch
            {
                "zh-TW" => "民國",
                "ja-JP" => "中華民国",
                _ => "民国"
            };
            var yearSeparator = languageTag == "ja-JP" ? "・" : "、";
            var westernYearSeparator = languageTag == "ja-JP" ? "・" : "、";
            var dateSuffix = languageTag == "ja-JP" ? "年" : "";
            return $"{eraName}{firstYear}{yearSeparator}{secondYear}年（{firstDate}{dateSuffix}{westernYearSeparator}{secondDate}{dateSuffix}）";
        }

        var noDate = Regex.Match(sourceDate, @"ND\s*\(\s*(?<approx>ca\.)?\s*(?<year>[0-9]{4})\s*\)", RegexOptions.IgnoreCase);
        if (noDate.Success)
        {
            var approximate = noDate.Groups["approx"].Success;
            if (languageTag == "ja-JP")
            {
                return $"日付不詳（{(approximate ? "約" : "")}{noDate.Groups["year"].Value}年）";
            }

            var qualifier = languageTag == "zh-TW"
                ? (approximate ? "約" : "")
                : (approximate ? "约" : "");
            return languageTag == "zh-TW"
                ? $"未標日期（{qualifier}{noDate.Groups["year"].Value}）"
                : $"未标日期（{qualifier}{noDate.Groups["year"].Value}）";
        }

        var overprint = Regex.Match(sourceDate,
            @"^(?<month>[0-9]{1,2})-(?<year>[0-9]{4})(?:\s*-\s*Overprint\s+|\s*\(\s*Overprint\s+)(?<overprint>[0-9]{4})\s*\)?$",
            RegexOptions.IgnoreCase);
        if (overprint.Success)
        {
            var month = overprint.Groups["month"].Value;
            var year = overprint.Groups["year"].Value;
            var overprintYear = overprint.Groups["overprint"].Value;
            if (languageTag == "ja-JP")
            {
                return $"{year}年{month}月（{overprintYear}年加刷）";
            }

            return languageTag == "zh-TW"
                ? $"{year}年{month}月（{overprintYear}年加印）"
                : $"{year}年{month}月（{overprintYear}年加印）";
        }

        return sourceDate;
    }

