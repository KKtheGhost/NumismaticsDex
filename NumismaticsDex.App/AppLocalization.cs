        private static string ToChineseNumber(int value)
    {
        string[] digits = ["零", "一", "二", "三", "四", "五", "六", "七", "八", "九"];
        if (value <= 10)
        {
            return value == 10 ? "十" : digits[value];
        }
        if (value < 20)
        {
            return "十" + digits[value % 10];
        }

        var tens = value / 10;
        var ones = value % 10;
        return digits[tens] + "十" + (ones == 0 ? "" : digits[ones]);
    }

