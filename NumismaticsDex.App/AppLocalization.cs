    public static string ResearchDescription(Banknote banknote, string languageTag) => banknote.Research is not { } research
        ? string.Empty
        : languageTag switch
        {
            "zh-TW" => research.TraditionalDescription,
            "en-US" => research.EnglishDescription,
            "ja-JP" => string.IsNullOrWhiteSpace(research.JapaneseDescription)
                ? research.EnglishDescription
                : research.JapaneseDescription,
            _ => research.SimplifiedDescription
        };

    public static string ResearchSourceName(Banknote banknote, string languageTag)
    {
        if (banknote.Research is not { } research)
        {
            return string.Empty;
        }

        if (languageTag == "en-US")
        {
            return research.SourceName;
        }

        if (!ResearchSourceTranslations.TryGetValue(research.SourceName, out var translated))
        {
            return research.SourceName;
        }

        return languageTag switch
        {
            "zh-TW" => translated.Traditional,
            "ja-JP" => translated.Japanese,
            _ => translated.Simplified
        };
    }

