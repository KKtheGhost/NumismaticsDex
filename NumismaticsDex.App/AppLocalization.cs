        }

        var segments = Regex.Split(text, "(\"[^\"]*\"|“[^”]*”|「[^」]*」)");
        var japaneseWords = JapaneseVariantWordTranslations
            .Concat(JapaneseVariantWordTranslationsExtra)
            .OrderByDescending(pair => pair.Key.Length)
            .ToArray();
        for (var segmentIndex = 0; segmentIndex < segments.Length; segmentIndex += 2)
        {
            foreach (var (sourceWord, japaneseWord) in japaneseWords)
            {
                segments[segmentIndex] = Regex.Replace(
                    segments[segmentIndex],
                    $@"\b{Regex.Escape(sourceWord)}\b",
                    japaneseWord,
                    RegexOptions.IgnoreCase);
            }
        }
        text = string.Concat(segments);
        text = Regex.Replace(text, @"\b([0-9]+(?:[.,][0-9]+)?)\s*x\s*([0-9]+(?:[.,][0-9]+)?)\s*mm\b", "$1 × $2 mm", RegexOptions.IgnoreCase);
        return Regex.Replace(text, @"\s+", " ").Trim();
    }

    public static string SearchText(Banknote banknote, string languageTag) => string.Join(
        ' ',
        banknote.Id,
        banknote.PickLabel,
        banknote.Issuer,
        banknote.Denomination,
        banknote.VariantDescription,
        banknote.Research?.SourceName,
        ResearchDescription(banknote, languageTag),
        ResearchTags(banknote, languageTag),
        string.Join(' ', banknote.Research is { } research ? research.Tags : Array.Empty<string>()),
        Issuer(banknote, languageTag),
        Denomination(banknote, languageTag),
        Variant(banknote, languageTag));
